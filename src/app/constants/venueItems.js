const venueLogo = (text, bg = 'f9f6ef', color = '6f5a38') =>
  `https://dummyimage.com/120x54/${bg}/${color}.png&text=${encodeURIComponent(text)}`

const venueAsset = (folder, fileName) => `/assets/venues/${folder}/${fileName}`

const venueGallery = (folder, venueName, fileNames) =>
  fileNames.map((fileName, index) => ({
    src: venueAsset(folder, fileName),
    alt:
      index === 0
        ? `${venueName} main view`
        : `${venueName} gallery image ${index}`,
  }))

const createVenue = ({
  id,
  title,
  location,
  vendorName,
  vendorLogoSrc,
  vendorLogoAlt,
  imageSrc,
  imageAlt,
  galleryImages,
  description,
  detailsDescription,
  placement,
  time,
  minGuests,
  maxGuests,
  priceValue,
  ratingValue,
  reviewCount,
  discountLabel = '',
  logoText,
}) => ({
  id,
  imageSrc,
  imageAlt,
  title,
  description,
  detailsDescription,
  guestText: `Guests: ${minGuests} - ${maxGuests}`,
  priceText: `${priceValue}$/Night`,
  discountLabel,
  vendorName,
  vendorLocation: location,
  ratingValue,
  reviewCount,
  detailBadgeText: placement === 'indoor' ? 'Indoor' : 'Outdoor',
  supportingInfoText: `Guests: ${minGuests} - ${maxGuests}`,
  peopleLabel: 'Number of people',
  datePlaceholder: 'Select Reservation Date',
  timePlaceholder: 'Select Reservation Time',
  actionButtonText: 'Add to Cart',
  location,
  placement,
  time,
  minGuests,
  maxGuests,
  priceValue,
  vendorLogoSrc: vendorLogoSrc || venueLogo(logoText || vendorName),
  vendorLogoAlt: vendorLogoAlt || `${vendorName} logo`,
  galleryImages:
    Array.isArray(galleryImages) && galleryImages.length > 0
      ? galleryImages
      : [
          {
            src: imageSrc,
            alt: imageAlt,
          },
        ],
})

